void	signal_set(int type)
{
	if (type == 0)
	{
		signal(SIGINT, ign);
		signal(SIGQUIT, ign);
	}
	if (type == 1)
	{
		signal(SIGINT, signal_hd);
		signal(SIGQUIT, signal_hd);
	}
	if (type == 2)
	{
		signal(SIGINT, signal_execve);
		signal(SIGQUIT, signal_execve);
	}
}
